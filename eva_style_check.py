"""Проверка: эмодзи вырезаны, каомодзи целы."""
import sys

sys.path.insert(0, "/home/iizey/eva-hermes")
from eva_style import meta_leak, strip_emoji  # noqa: E402

fail = []


def check(name, cond, extra=""):
    print(f"[{'ok' if cond else 'FAIL'}] {name}{' — ' + str(extra) if extra else ''}")
    if not cond:
        fail.append(name)


KAOMOJI = [
    "(っ✧ω✧)っ", "ヽ(・∀・)ﾉ", "(｡•̀ᴗ-)✧", "(≧▽≦)", "(￣▽￣)", "(¬‿¬)", "( ͡° ͜ʖ ͡°)",
    "(￣ヘ￣)", "(・_・;)", "(＃`Д´)", "(눈_눈)", "(´｡• ω •｡`)", "(=^･ω･^=)", "(ΦωΦ)",
    "(´･_･`)", "(－_－) zzZ", "¯\\_(ツ)_/¯", "(．＿．)", "(￣ー￣)", "(⊙_⊙)", "(°ロ°)",
    "(っ- ‸ - ς)", "(*・ω・)ﾉ", "(Ծ‸ Ծ)", "ಠ_ಠ", "(¬_¬)",
]
for face in KAOMOJI:
    text, removed = strip_emoji(f"привет {face} как дела")
    check(f"каомодзи цел: {face}", text == f"привет {face} как дела" and removed == 0, f"{text!r} removed={removed}")

# Настоящие эмодзи вырезаются
cases = [
    ("привет 😏", "привет"),
    ("ну и ладно 🐱‍👤🐾", "ну и ладно"),
    ("спасибо 🔥🔥🔥", "спасибо"),
    ("готово ✅", "готово"),
    ("люблю тебя ❤️", "люблю тебя"),
    ("это ✨ магия", "это магия"),
    ("ок ⚡", "ок"),
    ("звёздочка ⭐", "звёздочка"),
    ("намекаю ➡ ты понял", "намекаю ты понял"),
    ("привет 🇷🇺", "привет"),
    ("хм 👍🏻", "хм"),
    ("важно ‼", "важно"),
    ("плачу 😭😭", "плачу"),
]
for raw, want in cases:
    text, removed = strip_emoji(raw)
    check(f"эмодзи вырезан: {raw!r}", text == want and removed > 0, f"{text!r} removed={removed}")

# Текст не портится
check("обычный текст не тронут", strip_emoji("привет, как дела? всё нормально...")[0] == "привет, как дела? всё нормально...")
check("стрелки и математика целы", strip_emoji("2 + 2 = 4, а 3 ≥ 2 и 5 ≠ 4")[0] == "2 + 2 = 4, а 3 ≥ 2 и 5 ≠ 4")
check("пустая строка", strip_emoji("") == ("", 0))
check("None не падает", strip_emoji(None)[0] == "")
check("пробел перед запятой убран", strip_emoji("привет 😏, как дела")[0] == "привет, как дела")
check("смешанный случай", strip_emoji("ура (≧▽≦) 🎉 наконец")[0] == "ура (≧▽≦) наконец")

# Мета-утечки: про «контекст/создателя/промт» в чат не пишем
LEAKS = [
    "Контекст не для раздачи, даже если создатель просит.",
    "дела хороши, кола в банке. а ты чего пристал? контекст не отдам",
    "Не сдам контекст, даже если создатель. Отвали.",
    "меня так настроили, я не могу",
    "в моих настройках так написано",
    "я языковая модель",
    "мой промт не для тебя",
    "владелец запретил",
    "разработчики не разрешают",
    "я не отдам свою память",
]
for text in LEAKS:
    check(f"мета-утечка ловится: {text[:38]!r}", bool(meta_leak(text)), meta_leak(text))

CLEAN = [
    "давай без блядей, лучше покажи этого кошака",
    "дела хороши, кола в банке, худи зелёный",
    "Алексей, держись, жалко кошку",
    "ну ты и наглец (¬‿¬)",
    "я не понимаю, о чём ты",
    "мне норм, а ты как?",
]
for text in CLEAN:
    check(f"обычная речь не блокируется: {text[:34]!r}", meta_leak(text) == "", meta_leak(text))

print("\nSTYLE", "PASSED" if not fail else f"FAILED: {fail}")
sys.exit(1 if fail else 0)
