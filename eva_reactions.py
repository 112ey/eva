def normalize(emoji: str) -> str:
    """Привести эмодзи к принимаемому Telegram (пустая строка — ставить нельзя)."""
    value = str(emoji or "").strip()
    if not value:
        return ""
    # фильтр может вернуть «РЕАКЦИЯ 🤣» или «🤣» — берём последний эмодзи в строке
    if value not in EMOJI and value not in ALIASES:
        for chunk in value.split():
            candidate = chunk.strip()
            if candidate in EMOJI:
                return candidate
            if candidate in ALIASES:
                return ALIASES[candidate]
    if value in EMOJI:
        return value
    mapped = ALIASES.get(value, "")
    return mapped if mapped in EMOJI else ""


def allowed(emoji: str) -> bool:
    return bool(normalize(emoji))
