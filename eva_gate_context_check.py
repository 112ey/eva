"""Проверка: фильтр вообще смотрит на предыдущий контекст или решает по одной строке?

Одна и та же фраза подаётся с разной историей — вердикты должны различаться.
"""
import os
import sys

os.environ.setdefault("HERMES_HOME", "/home/iizey/eva-home")
sys.path.insert(0, "/home/iizey/eva-hermes")

from plugins.platforms.telegram.eva_gate import should_reply  # noqa: E402

PAIRS = [
    ("Фраза после ссоры",
     ["[Алексей] ты вообще не мужик", "[Паша] а ты дебил", "[Алексей] иди отсюда"],
     "[Паша] ну и что дальше", True),
    ("Та же фраза после мемов",
     ["[Паша] вот мем", "[Максим] ахахах", "[Алексей] лол, скинь ещё"],
     "[Паша] ну и что дальше", False),
    ("Односложный ответ на её вопрос",
     ["[Ева] как называется эта группа?"],
     "[Владелец] молва", True),
    ("Односложное «ок» после её сообщения",
     ["[Ева] тогда встречаемся в три"],
     "[Паша] ок", True),
    ("Односложное слово НЕ ей",
     ["[Паша] я завтра в школу не пойду", "[Максим] ясно"],
     "[Алексей] молва", False),
    ("Короткое «ок» после ссоры",
     ["[Алексей] ты мне надоел", "[Паша] сам такой", "[Алексей] всё, я обиделся"],
     "[Паша] ок", True),
    ("Короткое «ок» в болтовне",
     ["[Паша] я в два освобожусь", "[Максим] понял, тогда в три"],
     "[Паша] ок", False),
]

fail = []
for name, history, incoming, expected in PAIRS:
    verdict = should_reply(history, incoming)
    ok = verdict is expected
    print(f"[{'ok' if ok else '!!'}] {name}: вердикт={verdict!r} (ждали {expected!r})")
    if not ok:
        fail.append(name)

print("\nGATE-CONTEXT", "PASSED" if not fail else f"РАСХОЖДЕНИЯ: {fail}")
