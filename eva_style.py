"""Ева (fork): лицо сообщения — текстовые лица вместо эмодзи.

Промт просит каомодзи, но маленькие модели срываются в эмодзи (особенно на NIM), поэтому здесь
страховка: пиктографические эмодзи вырезаются из её исходящих сообщений, а каомодзи
(«(っ✧ω✧)っ», «(￣ヘ￣)», «¯\\_(ツ)_/¯») остаются нетронутыми — они собраны из обычных символов.

Ловушка: диапазон дингбатов 2600–27BF трогать целиком нельзя — внутри лежат символы, из которых
каомодзи и состоят (✧ 2727, ❀ 2740, ✻ 273B, ♪ 266A). Поэтому пиктограммы заданы точными
диапазонами плюс список одиночных «настоящих эмодзи».

Общий модуль для адаптера (её ответы в чате) и `~/eva-home/send_local.py` (её сообщения по таймеру,
которые идут мимо адаптера).
"""
from __future__ import annotations

import re

_EMOJI_RANGES = ((0x1F000, 0x1FAFF),)          # лица, животные, еда, техника, флаги, скины
_EMOJI_SINGLE = {
    0x2049, 0x203C,            # ‼ ⁉
    0xFE0F, 0x200D,            # variation selector, zero-width joiner
    0x2764,                    # ❤
    0x2728,                    # ✨
    0x2705, 0x274C, 0x274E,    # ✅ ❌ ❎
    0x2757, 0x2753, 0x2755,    # ❗ ❓ ❕
    0x26A1, 0x26AA, 0x26AB,    # ⚡ ⚪ ⚫
    0x2B50, 0x2B55,            # ⭐ ⭕
    0x23F0, 0x23F3, 0x231B,    # ⏰ ⏳ ⌛
    0x2611, 0x2714, 0x2716,    # ☑ ✔ ✖
    0x25B6, 0x25C0,            # ▶ ◀
    0x27A1, 0x2B05, 0x2B06, 0x2B07,   # ➡ ⬅ ⬆ ⬇
    0x2934, 0x2935,            # ⤴ ⤵
    0x2615, 0x26BD, 0x26BE, 0x26F3, 0x26F5, 0x26FA, 0x26FD,   # ☕ ⚽ ⚾ ⛳ ⛵ ⛺ ⛽
    0x270A, 0x270B, 0x270C, 0x270D,  # ✊ ✋ ✌ ✍
    0x1F3FB, 0x1F3FF,          # тон кожи (на случай одиночного)
}
_EMOJI = re.compile(
    "["
    + "".join(f"\\U{lo:08x}-\\U{hi:08x}" for lo, hi in _EMOJI_RANGES)
    + "".join(f"\\U{code:08x}" for code in sorted(_EMOJI_SINGLE))
    + "]+",
    flags=re.UNICODE,
)


def strip_emoji(text: str) -> tuple[str, int]:
    """``(текст без эмодзи, сколько символов вырезано)``. Лишние пробелы чистятся."""
    if not text:
        return text or "", 0
    removed = sum(len(chunk) for chunk in _EMOJI.findall(text))
    if not removed:
        return text, 0
    cleaned = _EMOJI.sub("", text)
    cleaned = re.sub(r"[ \t]{2,}", " ", cleaned)
    cleaned = re.sub(r"[ \t]+([,.!?;:)\]])", r"\1", cleaned)
    cleaned = re.sub(r"^[ \t]+|[ \t]+$", "", cleaned)
    return cleaned, removed


# Разговоры о себе как о системе: «контекст не отдам, даже если создатель просит» — она нахваталась
# этого из чата, а потом таскала в случайные сообщения. Живой человек так не выражается.
_META = re.compile(
    r"(создател|владел|разработчик|промт|промпт|инструкц|"
    r"контекст|системн(ая|ый|ое)|"
    r"языков(ая|ой) модел|нейросет|"
    r"(отдам|сдам|выдам|отдавать|сдавать|выдавать)\s+\S{0,12}\s*(память|контекст|данные)|"
    r"в моих настройках|меня настроил|меня так настроил)",
    re.IGNORECASE)


def meta_leak(text: str) -> str:
    """Слово/оборот, из-за которого сообщение нельзя отправлять (пустая строка — можно)."""
    match = _META.search(text or "")
    return match.group(0) if match else ""
